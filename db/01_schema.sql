-- ============================================================================
-- 01_schema.sql  --  VaxTrack tables, constraints, identity keys, indexes
-- Owner  : vaxapp (run as vaxapp, on an empty schema; use 99_drop_all.sql to reset)
-- Notes  : * IDs are identity columns (no hard-coded IDs anywhere).
--          * "DOB not in the future" cannot be a CHECK (SYSDATE is not allowed
--            in CHECK), so it is enforced by trg_newborn_dob_check (08_triggers.sql).
-- ============================================================================
SET DEFINE OFF
SET ECHO ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- ---------------------------------------------------------------- clinics
CREATE TABLE clinics (
  clinic_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  clinic_name  VARCHAR2(100) NOT NULL,
  city         VARCHAR2(60)  NOT NULL,
  phone        VARCHAR2(20),
  CONSTRAINT pk_clinics      PRIMARY KEY (clinic_id),
  CONSTRAINT uq_clinics_name UNIQUE (clinic_name)
);

-- -------------------------------------------------------------- guardians
-- phone is UNIQUE because register_newborn reuses a guardian found by phone.
CREATE TABLE guardians (
  guardian_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  full_name    VARCHAR2(100) NOT NULL,
  phone        VARCHAR2(15)  NOT NULL,
  email        VARCHAR2(120),
  address      VARCHAR2(250),
  CONSTRAINT pk_guardians       PRIMARY KEY (guardian_id),
  CONSTRAINT uq_guardians_phone UNIQUE (phone),
  CONSTRAINT ck_guardians_phone CHECK (REGEXP_LIKE(phone, '^[0-9+ -]{7,15}$'))
);

-- -------------------------------------------------------------- app_users
CREATE TABLE app_users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  username       VARCHAR2(50)  NOT NULL,
  password_hash  VARCHAR2(100) NOT NULL,
  role           VARCHAR2(10)  NOT NULL,
  full_name      VARCHAR2(100) NOT NULL,
  clinic_id      NUMBER,
  guardian_id    NUMBER,
  CONSTRAINT pk_app_users          PRIMARY KEY (user_id),
  CONSTRAINT uq_app_users_username UNIQUE (username),
  CONSTRAINT ck_app_users_role     CHECK (role IN ('ADMIN','NURSE','PARENT')),
  CONSTRAINT ck_app_users_scope    CHECK (role = 'ADMIN'
                                       OR (role = 'NURSE'  AND clinic_id   IS NOT NULL)
                                       OR (role = 'PARENT' AND guardian_id IS NOT NULL)),
  CONSTRAINT fk_app_users_clinic   FOREIGN KEY (clinic_id)   REFERENCES clinics (clinic_id),
  CONSTRAINT fk_app_users_guardian FOREIGN KEY (guardian_id) REFERENCES guardians (guardian_id)
);

-- --------------------------------------------------------------- newborns
CREATE TABLE newborns (
  baby_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  guardian_id      NUMBER        NOT NULL,
  clinic_id        NUMBER        NOT NULL,
  full_name        VARCHAR2(100) NOT NULL,
  gender           CHAR(1)       NOT NULL,
  date_of_birth    DATE          NOT NULL,
  birth_weight_kg  NUMBER(4,2),
  created_at       DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_newborns          PRIMARY KEY (baby_id),
  CONSTRAINT ck_newborns_gender   CHECK (gender IN ('M','F','O')),
  CONSTRAINT ck_newborns_weight   CHECK (birth_weight_kg IS NULL OR birth_weight_kg BETWEEN 0.5 AND 9.99),
  CONSTRAINT fk_newborns_guardian FOREIGN KEY (guardian_id) REFERENCES guardians (guardian_id),
  CONSTRAINT fk_newborns_clinic   FOREIGN KEY (clinic_id)   REFERENCES clinics (clinic_id)
);

-- --------------------------------------------------------- vaccine_master
-- The immunization schedule is DATA. Ages are days from DOB (1 month = 30 days).
-- is_regional = 'Y' marks doses given only in endemic districts (JE).
CREATE TABLE vaccine_master (
  vaccine_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  vaccine_name    VARCHAR2(60)  NOT NULL,
  disease_covered VARCHAR2(150) NOT NULL,
  dose_number     NUMBER(2)     NOT NULL,
  age_label       VARCHAR2(30)  NOT NULL,
  min_age_days    NUMBER(5)     NOT NULL,
  due_age_days    NUMBER(5)     NOT NULL,
  max_age_days    NUMBER(5)     NOT NULL,
  route           VARCHAR2(30)  NOT NULL,
  is_regional     CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT pk_vaccine_master   PRIMARY KEY (vaccine_id),
  CONSTRAINT uq_vaccine_dose     UNIQUE (vaccine_name, dose_number),
  CONSTRAINT ck_vaccine_dose_no  CHECK (dose_number >= 0),
  CONSTRAINT ck_vaccine_ages     CHECK (min_age_days >= 0
                                    AND min_age_days <= due_age_days
                                    AND due_age_days <= max_age_days),
  CONSTRAINT ck_vaccine_regional CHECK (is_regional IN ('Y','N'))
);

-- ------------------------------------------------------ vaccine_inventory
-- One row per batch per clinic.
CREATE TABLE vaccine_inventory (
  inventory_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  clinic_id            NUMBER       NOT NULL,
  vaccine_id           NUMBER       NOT NULL,
  batch_no             VARCHAR2(40) NOT NULL,
  expiry_date          DATE         NOT NULL,
  quantity             NUMBER(6) DEFAULT 0  NOT NULL,
  low_stock_threshold  NUMBER(6) DEFAULT 10 NOT NULL,
  CONSTRAINT pk_vaccine_inventory PRIMARY KEY (inventory_id),
  CONSTRAINT uq_inventory_batch   UNIQUE (clinic_id, vaccine_id, batch_no),
  CONSTRAINT ck_inventory_qty     CHECK (quantity >= 0),
  CONSTRAINT ck_inventory_thresh  CHECK (low_stock_threshold >= 0),
  CONSTRAINT fk_inventory_clinic  FOREIGN KEY (clinic_id)  REFERENCES clinics (clinic_id),
  CONSTRAINT fk_inventory_vaccine FOREIGN KEY (vaccine_id) REFERENCES vaccine_master (vaccine_id)
);

-- ----------------------------------------------------------- dose_records
CREATE TABLE dose_records (
  record_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  baby_id           NUMBER NOT NULL,
  vaccine_id        NUMBER NOT NULL,
  scheduled_date    DATE   NOT NULL,
  administered_date DATE,
  status            VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  inventory_id      NUMBER,
  administered_by   NUMBER,
  is_late           CHAR(1) DEFAULT 'N' NOT NULL,
  remarks           VARCHAR2(500),
  CONSTRAINT pk_dose_records      PRIMARY KEY (record_id),
  CONSTRAINT uq_dose_baby_vaccine UNIQUE (baby_id, vaccine_id),
  CONSTRAINT ck_dose_status       CHECK (status IN ('PENDING','DONE','OVERDUE')),
  CONSTRAINT ck_dose_late         CHECK (is_late IN ('Y','N')),
  CONSTRAINT ck_dose_done_date    CHECK ((status = 'DONE' AND administered_date IS NOT NULL)
                                      OR (status <> 'DONE' AND administered_date IS NULL)),
  CONSTRAINT fk_dose_baby         FOREIGN KEY (baby_id)         REFERENCES newborns (baby_id),
  CONSTRAINT fk_dose_vaccine      FOREIGN KEY (vaccine_id)      REFERENCES vaccine_master (vaccine_id),
  CONSTRAINT fk_dose_inventory    FOREIGN KEY (inventory_id)    REFERENCES vaccine_inventory (inventory_id),
  CONSTRAINT fk_dose_user         FOREIGN KEY (administered_by) REFERENCES app_users (user_id)
);

-- ---------------------------------------------------------------- alerts
CREATE TABLE alerts (
  alert_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  baby_id     NUMBER,
  record_id   NUMBER,
  clinic_id   NUMBER,
  alert_type  VARCHAR2(10)  NOT NULL,
  message     VARCHAR2(400) NOT NULL,
  alert_date  DATE DEFAULT SYSDATE NOT NULL,
  is_read     CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT pk_alerts        PRIMARY KEY (alert_id),
  CONSTRAINT ck_alerts_type   CHECK (alert_type IN ('DUE_SOON','OVERDUE','LATE_DOSE','LOW_STOCK','EXPIRY')),
  CONSTRAINT ck_alerts_read   CHECK (is_read IN ('Y','N')),
  CONSTRAINT fk_alerts_baby   FOREIGN KEY (baby_id)   REFERENCES newborns (baby_id),
  CONSTRAINT fk_alerts_record FOREIGN KEY (record_id) REFERENCES dose_records (record_id),
  CONSTRAINT fk_alerts_clinic FOREIGN KEY (clinic_id) REFERENCES clinics (clinic_id)
);

-- ------------------------------------------------------------- audit_log
-- Filled by trigger only. No FKs on purpose: audit rows must outlive the rows they describe.
CREATE TABLE audit_log (
  audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  table_name  VARCHAR2(30) NOT NULL,
  record_id   NUMBER,
  action      VARCHAR2(10) NOT NULL,
  old_value   VARCHAR2(4000),
  new_value   VARCHAR2(4000),
  changed_by  VARCHAR2(100),
  changed_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_audit_log    PRIMARY KEY (audit_id),
  CONSTRAINT ck_audit_action CHECK (action IN ('INSERT','UPDATE','DELETE'))
);

-- -------------------------------------------------------------- test_log
CREATE TABLE test_log (
  test_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  tc_code      VARCHAR2(20)   NOT NULL,
  description  VARCHAR2(300)  NOT NULL,
  expected     VARCHAR2(1000),
  actual       VARCHAR2(1000),
  result       VARCHAR2(4)    NOT NULL,
  run_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_test_log   PRIMARY KEY (test_id),
  CONSTRAINT ck_test_result CHECK (result IN ('PASS','FAIL'))
);

-- --------------------------------------------------------------- indexes
-- dose_records(baby_id) is already covered by the leading column of uq_dose_baby_vaccine.
CREATE INDEX ix_app_users_clinic    ON app_users (clinic_id);
CREATE INDEX ix_app_users_guardian  ON app_users (guardian_id);
CREATE INDEX ix_newborns_guardian   ON newborns (guardian_id);
CREATE INDEX ix_newborns_clinic     ON newborns (clinic_id);
CREATE INDEX ix_newborns_name       ON newborns (UPPER(full_name));
CREATE INDEX ix_dose_status_sched   ON dose_records (status, scheduled_date);
CREATE INDEX ix_dose_vaccine        ON dose_records (vaccine_id);
CREATE INDEX ix_dose_inventory      ON dose_records (inventory_id);
CREATE INDEX ix_inventory_fefo      ON vaccine_inventory (clinic_id, vaccine_id, expiry_date);
CREATE INDEX ix_inventory_vaccine   ON vaccine_inventory (vaccine_id);
CREATE INDEX ix_alerts_clinic_read  ON alerts (clinic_id, is_read);
CREATE INDEX ix_alerts_baby         ON alerts (baby_id);
CREATE INDEX ix_alerts_record_type  ON alerts (record_id, alert_type);
CREATE INDEX ix_audit_table_record  ON audit_log (table_name, record_id);
